const CHIAVE = "palio.lingua";
let __lingua = null;

export function linguaAttiva() {
  if (__lingua) return __lingua;
  try { __lingua = localStorage.getItem(CHIAVE) === "en" ? "en" : "it"; }
  catch (e) { __lingua = "it"; }
  return __lingua;
}

export function impostaLingua(l) {
  __lingua = l === "en" ? "en" : "it";
  try { localStorage.setItem(CHIAVE, __lingua); } catch (e) { /* niente */ }
  return __lingua;
}

// Traduce un testo. In italiano, e per tutto cio' che non e' in tabella,
// restituisce quello che ha ricevuto.
export function T(testo) {
  if (linguaAttiva() !== "en") return testo;
  if (typeof testo !== "string") return testo;
  const secco = testo.trim();
  let tradotto = EN[secco];
  if (tradotto === undefined) {
    // niente in tabella: si provano i modelli, che tengono dentro i nomi
    for (let i = 0; i < MODELLI.length; i += 1) {
      const [re, sost] = MODELLI[i];
      if (re.test(secco)) { tradotto = secco.replace(re, sost); break; }
    }
  }
  if (tradotto === undefined) return testo;
  // conserva gli spazi/a capo attorno al testo originale
  const pre = testo.slice(0, testo.indexOf(secco));
  const post = testo.slice(testo.indexOf(secco) + secco.length);
  return pre + tradotto + post;
}

// ── TRADUZIONE DI QUEL CHE E' GIA' A SCHERMO ────────────────────────────────
// Si traducono i nodi di testo e gli attributi che si leggono (title,
// placeholder, aria-label). Il confronto e' per testo esatto, quindi nomi di
// Contrade, cavalli, fantini e numeri passano intatti.
const ATTRIBUTI = ["title", "placeholder", "aria-label", "data-label"];

export function traduciAlbero(radice) {
  if (linguaAttiva() !== "en" || !radice) return;
  try {
    const doc = radice.ownerDocument || document;
    const cammino = doc.createTreeWalker(radice, NodeFilter.SHOW_TEXT, null);
    const nodi = [];
    let n; while ((n = cammino.nextNode())) nodi.push(n);
    nodi.forEach((t) => {
      const orig = t.nodeValue;
      if (!orig || !orig.trim()) return;
      const tradotto = T(orig);
      if (tradotto !== orig) t.nodeValue = tradotto;
    });
    const elementi = radice.querySelectorAll ? radice.querySelectorAll("*") : [];
    elementi.forEach((el) => {
      ATTRIBUTI.forEach((a) => {
        const v = el.getAttribute && el.getAttribute(a);
        if (!v) return;
        const tr = T(v);
        if (tr !== v) el.setAttribute(a, tr);
      });
      if (el.tagName === "INPUT" && el.type === "button" && el.value) {
        const tr = T(el.value); if (tr !== el.value) el.value = tr;
      }
    });
  } catch (e) { /* la traduzione non deve mai fermare il gioco */ }
}

// Osserva quello che il gioco AGGIUNGE alla pagina (pannelli, overlay, elenchi)
// e lo traduce appena compare. Non si guardano le MODIFICHE di testo: quelle
// sono numeri e nomi che cambiano a ogni fotogramma, e passarci sopra a ogni
// frame sarebbe sprecato — i messaggi scritti li traduce showMessage.
let __osservatore = null;
export function avviaTraduzione() {
  if (linguaAttiva() !== "en") return;
  traduciAlbero(document.body);
  if (__osservatore) return;
  try {
    __osservatore = new MutationObserver((mut) => {
      mut.forEach((m) => {
        m.addedNodes && m.addedNodes.forEach((n) => {
          if (n.nodeType === 1) traduciAlbero(n);
          else if (n.nodeType === 3 && n.nodeValue && n.nodeValue.trim()) {
            const tr = T(n.nodeValue); if (tr !== n.nodeValue) n.nodeValue = tr;
          }
        });
      });
    });
    __osservatore.observe(document.body, { childList: true, subtree: true });
  } catch (e) { /* niente */ }
}
